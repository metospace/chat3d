export function generationReviewPrompt(workflow: 'agent' | 'single' | 'data' = 'agent'): string {
  const common = '统一采用高质量目标，完整保留用户明确需求与修改范围。质量目标不扩大编辑权限，不改变位置锁，也不以增加零件数或消耗预算代替质量。具体造型与风格遵循主提示词及用户要求的优先级，本节只规定当前工作流的复核与交付规则，不另设风格。';
  const evidence = '几何与数据检查不等于视觉验收。pass必须有当前版本真实且适用的证据；缺少证据、不可见结构或无法判断的项目如实保留待核对，不把生成成功说成精确还原或保证合格。软件几何图不能验收材质。所有修改仍须人工确认。';
  const workflowText = workflow === 'data'
    ? '当前为数据生成流程：按现有输出约定生成并校验数据；未执行真实视觉复核时，交付必须注明未经视觉验收，不宣称已经通过组件多视角验收。'
    : workflow === 'single'
      ? '当前为单次兼容生成：只生成一个合法JSON命令批。此路径不执行多轮视觉复核与修复；summary必须说明是未经视觉验收的数据草稿，不宣称已经通过组件多视角验收。'
      : '当前为多轮建模流程：完成结构后对受影响组件进行多视角近景、必要的底部或遮挡诊断及全景复核，保留六项细节验收。可指定当前修正的组件取图，完整复核计划支持分页；真实图片返回后的下一轮才能提交相关验收。依据明确缺陷局部修复，修复后重新取得当前版本证据，不为填写清单重复取图，也不为unknown无限优化。达到用户目标即可提交待确认预览；受阻时保留真实未完成项。';
  const limits = workflow === 'single'
    ? '沿用现有传输与输出限制；多轮任务预算监控和视觉修复仅适用于多轮流程。质量目标不增加预算，不承诺固定耗时或还原精度。'
    : '时间、轮数和已报告Token服从用户现有上限，不新增或扩大预算；到限保留阶段草稿和未完成项，不伪造通过，不承诺固定耗时或还原精度。';
  return `# 生成复核与交付\n${common}\n${evidence}\n${workflowText}\n${limits}`;
}
