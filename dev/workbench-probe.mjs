// Checks the migrated workbench controls render as antd in the real browser.
import {chromium} from 'playwright-core';
import {browserPath} from '../e2e/config.mjs';
const base=process.argv[2]??'http://localhost:1420';
const browser=await chromium.launch({executablePath:browserPath(),headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('console',m=>{if(m.type()==='error')errors.push(m.text().slice(0,120));});
const step=async(name,fn)=>{try{return await fn();}catch(error){console.log('STEP FAILED:',name,String(error).split('\n')[0]);throw error;}};
const result={};
await page.goto(base,{waitUntil:'networkidle'});
await step('new project',()=>page.getByRole('button',{name:'新建空白项目'}).click());
await page.waitForTimeout(3000);
result.url=page.url();
result.radix=await page.locator('[class*="rt-BaseButton"]').count();
result.antdButtons=await page.locator('.viewport-bottom-bar .ant-btn').count();
result.barBox=await page.locator('.viewport-bottom-bar').boundingBox();
const open=page.getByRole('button',{name:'显示选项'});
result.triggerVisible=await open.isVisible();
await step('open display',()=>open.click({force:true}));
await page.waitForTimeout(500);
const panel=page.locator('.viewport-display-panel');
result.panelCount=await panel.count();
result.panelBox=await panel.boundingBox();
result.tilesRow=await page.locator('.display-background-tiles').evaluate(el=>getComputedStyle(el).flexDirection).catch(()=>'missing');
await step('close display',()=>page.getByRole('button',{name:'关闭显示设置'}).click({force:true}));
await page.waitForTimeout(400);
result.panelAfterClose=await panel.count();
result.horizontalOverflow=await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
result.errors=errors.slice(0,3);
console.log(JSON.stringify(result,null,1));
await browser.close();
