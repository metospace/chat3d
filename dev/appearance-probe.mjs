import {chromium} from 'playwright-core';
import {browserPath} from '../e2e/config.mjs';
const base=process.argv[2]??'http://localhost:1420';
const browser=await chromium.launch({executablePath:browserPath(),headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('console',m=>{if(m.type()==='error')errors.push(m.text().slice(0,120));});
await page.goto(base,{waitUntil:'networkidle'});
await page.getByRole('button',{name:'设置',exact:true}).click();
await page.waitForTimeout(900);
const before=await page.evaluate(()=>document.documentElement.dataset.appearance);
await page.getByRole('combobox',{name:'应用外观'}).click();
await page.waitForTimeout(400);
await page.locator('.ant-select-item-option',{hasText:'深色'}).first().click();
await page.waitForTimeout(500);
const after=await page.evaluate(()=>document.documentElement.dataset.appearance);
const stored=await page.evaluate(()=>localStorage.getItem('chat3d.appearance.v1'));
const bg=await page.evaluate(()=>getComputedStyle(document.body).backgroundColor);
console.log(JSON.stringify({before,after,stored,bg,errors},null,1));
await browser.close();
