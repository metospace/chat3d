import {chromium} from 'playwright-core';
import {browserPath} from '../e2e/config.mjs';
const base=process.argv[2]??'http://localhost:1420';
const browser=await chromium.launch({executablePath:browserPath(),headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('console',m=>{if(m.type()==='error')errors.push(m.text().slice(0,120));});
const out={};
await page.goto(base,{waitUntil:'networkidle'});
await page.getByRole('button',{name:'新建空白项目'}).click();
await page.waitForTimeout(2500);
await page.getByRole('button',{name:'切换视角'}).click();
await page.waitForTimeout(500);
out.menuCount=await page.locator('.studio-control-menu').count();
out.menuBox=await page.locator('.studio-control-menu').boundingBox().catch(()=>null);
out.innerPadding=await page.locator('.ant-popover-inner:has(.studio-control-menu)').evaluate(el=>getComputedStyle(el).padding).catch(()=>'missing');
out.itemCount=await page.locator('.studio-control-menu .studio-menu-item').count();
out.radix=await page.evaluate(()=>[...document.querySelectorAll('[class*="rt-BaseButton"]')].map(e=>(e.textContent||'').trim().slice(0,12)).slice(0,6));
out.errors=errors.slice(0,3);
console.log(JSON.stringify(out,null,1));
await browser.close();
