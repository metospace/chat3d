import assert from 'node:assert/strict';
import {createServer} from 'vite';
const server=await createServer({server:{middlewareMode:true},appType:'custom'});
try{
 const {buildRepairAgenda,REPAIR_AGENDA_LIMIT}=await server.ssrLoadModule('/src/ai/repairAgenda.ts');
 const {updateReferenceRepairs,referenceRepairReport,inspectReferenceRepair}=await server.ssrLoadModule('/src/domain/referenceRepairs.ts');
 const {createInitialDoc}=await server.ssrLoadModule('/src/store.ts');
 const {applyBatch}=await server.ssrLoadModule('/src/domain/commands.ts');
 const doc=applyBatch(createInitialDoc(),{operations:[{op:'createPrimitive',name:'主体壳体',parentId:null,materialId:'mat_gray',transform:{position:[0,0,0],rotationQuaternion:[0,0,0,1],scale:[1,1,1]},geometry:{type:'box',params:{width:1,height:1,depth:1}}}]}).doc;
 const id=doc.nodes[0].id;
 const difference={id:'body-depth',featureKey:'body-profile',nodeIds:[id],observed:'纵向过短',expected:'纵向是宽度的两倍',action:'将主体深度从1米修正为2米，保留宽高和位置',view:'side'};
 const repairs=referenceRepairReport(updateReferenceRepairs(doc,[],[difference],[]));
 const check=(criterion,status='unknown',nodeIds=[id])=>({criterion,status,evidence:criterion+'的当前画面依据',nodeIds});
 const review=(checks,revision=doc.revision)=>({componentId:id,revision,checks,visualEvidence:true});
 const input={document:doc,referenceRepairs:[],detailReviews:[],reviewIssues:[],completionBlockers:[],capturedRevision:-1,reviewedRevision:-1};
 const untouched=JSON.stringify(doc);
 const known=buildRepairAgenda({...input,referenceRepairs:repairs,detailReviews:[review([check('materials'),check('structure','fail')])],capturedRevision:doc.revision,reviewedRevision:doc.revision});
 assert.equal(known.nextAction,'repair');
 assert.deepEqual(known.defects.map(item=>item.source),['reference-difference','detail-fail']);
 assert.equal(known.defects[0].name,'主体壳体：body-profile');
 assert.equal(known.defects[0].action,difference.action);
 assert.deepEqual(known.defects[0].nodeIds,[id]);
 assert.deepEqual(known.defects[0].requiredViews,['side']);
 assert.equal(known.defects[0].changedSinceReported,false);
 assert.equal(known.defects[1].changedSinceReported,null,'detail review does not pretend to have a saved geometry fingerprint');
 assert.equal(known.unknownEvidence[0].criterion,'materials');
 assert.equal(known.advisory,true,'repair recommendation must not prohibit diagnostic capture');
 assert.equal(JSON.stringify(doc),untouched,'agenda does not change the scene');
 assert.equal(repairs[0].status,'unresolved');
 console.log('PASS explicit reference differences and known failures precede unknown evidence without a fabricated edit plan');

 const appearance=applyBatch(doc,{operations:[{op:'rename',targetId:id,name:'已修复'},{op:'setAppearance',targetId:id,baseColor:'#ffffff'}]}).doc;
 const unchanged=buildRepairAgenda({...input,document:appearance,referenceRepairs:repairs});
 assert.equal(unchanged.nextAction,'repair');
 assert.equal(unchanged.defects[0].changedSinceReported,false);
 assert.equal(inspectReferenceRepair(appearance,repairs[0]).changedSinceReported,false);
 const changed=applyBatch(doc,{operations:[{op:'updateParameters',targetId:id,geometry:{type:'box',params:{width:1,height:1,depth:2}}}]}).doc;
 const verification=buildRepairAgenda({...input,document:changed,referenceRepairs:repairs});
 assert.equal(verification.nextAction,'verify-repair');
 assert.equal(verification.defects[0].changedSinceReported,true);
 assert.equal(verification.totalDefects,1,'visual mutation does not itself resolve a difference');
 assert.deepEqual(verification.defects[0].requiredViews,['side']);
 const unrelated=structuredClone(doc);unrelated.revision++;
 unrelated.nodes.push({...structuredClone(doc.nodes[0]),id:'unrelated-node',name:'另一部件'});
 assert.equal(buildRepairAgenda({...input,document:unrelated,referenceRepairs:repairs}).nextAction,'repair','an unrelated visual mutation cannot repair the named defect');
 console.log('PASS material, rename and unrelated revision changes cannot resolve a reference shape defect; targeted mutation requests verification');

 const unknown=buildRepairAgenda({...input,detailReviews:[review([check('silhouette')])]});
 assert.equal(unknown.nextAction,'inspect');assert.equal(unknown.totalDefects,0);assert.equal(unknown.totalUnknownEvidence,1);
 const failed=buildRepairAgenda({...input,detailReviews:[review([check('silhouette','fail')])]});
 assert.equal(failed.nextAction,'repair');
 const stale=buildRepairAgenda({...input,document:appearance,detailReviews:[review([check('silhouette','fail')])]});
 assert.equal(stale.nextAction,'inspect');assert.equal(stale.totalDefects,1);assert.equal(stale.defects[0].changedSinceReported,null);
 const partial=buildRepairAgenda({...input,document:appearance,detailReviews:[review([check('silhouette','fail')]),review([check('materials')],appearance.revision)]});
 assert.equal(partial.totalDefects,1,'later partial reviews do not erase older unchecked criteria');
 const superseded=buildRepairAgenda({...input,document:appearance,detailReviews:[review([check('silhouette','fail')]),review([check('silhouette','pass')],appearance.revision)]});
 assert.equal(superseded.totalDefects,0,'later explicit criterion review supersedes an earlier failure');
 assert.equal(buildRepairAgenda({...input,capturedRevision:doc.revision}).nextAction,'review');
 assert.equal(buildRepairAgenda(input).nextAction,'inspect');
 const ready=buildRepairAgenda({...input,capturedRevision:doc.revision,reviewedRevision:doc.revision});
 assert.equal(ready.nextAction,'submit');assert.equal(ready.submissionRequiresExistingGates,true);
 console.log('PASS current evidence requests review, stale failures remain visible, and submit remains advisory');

 const absent=structuredClone(doc);absent.revision++;absent.nodes=[];
 const missing=buildRepairAgenda({...input,document:absent,referenceRepairs:repairs});
 assert.deepEqual(missing.defects[0].nodeIds,[]);assert.deepEqual(missing.defects[0].missingNodeIds,[id]);assert.deepEqual(missing.defects[0].componentIds,[]);
 const invalid=buildRepairAgenda({...input,detailReviews:[review([check('connections','fail',['nonexistent'])])]});
 assert.deepEqual(invalid.defects[0].nodeIds,[]);assert.deepEqual(invalid.defects[0].missingNodeIds,['nonexistent']);
 const blockers=buildRepairAgenda({...input,reviewIssues:['待核对轮廓'],completionBlockers:['缺少动态证据']});
 assert.ok(blockers.unknownEvidence.every(item=>item.nodeIds.length===0&&item.componentIds.length===0));
 assert.equal(blockers.nextAction,'inspect');assert.equal(blockers.totalDefects,0,'unstructured issue text is not parsed into fake named geometry defects');
 console.log('PASS absent and unstructured targets never invent editable node IDs');

 const many=Array.from({length:REPAIR_AGENDA_LIMIT+5},(_,index)=>({...difference,id:'difference-'+String(index).padStart(2,'0'),featureKey:'feature-'+index}));
 const manyRepairs=referenceRepairReport(updateReferenceRepairs(doc,[],many,[]));
 const manyIssues=Array.from({length:REPAIR_AGENDA_LIMIT+3},(_,index)=>'待核对项'+index);
 const bounded=buildRepairAgenda({...input,referenceRepairs:manyRepairs,detailReviews:[review([check('structure','fail')])],reviewIssues:manyIssues,completionBlockers:manyIssues});
 assert.equal(bounded.defects.length,REPAIR_AGENDA_LIMIT);assert.ok(bounded.defects.every(item=>item.source==='reference-difference'));
 assert.equal(bounded.totalDefects,many.length+1);assert.equal(bounded.remainingDefects,6);
 assert.equal(bounded.unknownEvidence.length,REPAIR_AGENDA_LIMIT);assert.equal(bounded.remainingUnknownEvidence,manyIssues.length*2-REPAIR_AGENDA_LIMIT);
 assert.equal(bounded.remainingReviewIssues,3);assert.equal(bounded.remainingCompletionBlockers,3);
 assert.deepEqual(bounded,buildRepairAgenda({...input,referenceRepairs:manyRepairs,detailReviews:[review([check('structure','fail')])],reviewIssues:manyIssues,completionBlockers:manyIssues}));
 const contract=Object.freeze({layout:'保留已声明的通道布局',assumptions:'尺寸沿用当前方案',materials:[{id:'mat_gray',baseColor:doc.materials[0].baseColor,roughness:doc.materials[0].roughness}],blueprints:[{key:'body',views:['front','side']}]});
 const shared=buildRepairAgenda({...input,sharedSceneContract:contract});
 assert.equal(shared.sharedSceneContract,contract,'forward shared current-source constraints without a second persistence or repaint path');
 assert.equal(buildRepairAgenda(input).sharedSceneContract,undefined);
 console.log('PASS bounded prioritized agenda exposes exact remaining counts and forwards optional shared source constraints');
}finally{await server.close();}
